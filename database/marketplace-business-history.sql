-- Additive Oracle migration. Run as SYS/SYSTEM in FREEPDB1 after stopping the Auth service.
-- Existing UUIDs, applications and original request payloads are preserved.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;
SET SERVEROUTPUT ON;
ALTER SESSION SET CONTAINER=FREEPDB1;
DECLARE n NUMBER;BEGIN
 SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='CF_AUTH' AND TABLE_NAME='CF_MARKETPLACE_REFERENCES';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE CF_AUTH.CF_MARKETPLACE_REFERENCES(MARKETPLACE_ID VARCHAR2(36) PRIMARY KEY,REFERENCE_PREFIX VARCHAR2(8) NOT NULL UNIQUE,NEXT_NUMBER NUMBER(12) NOT NULL CHECK(NEXT_NUMBER>0))';END IF;
 SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='CF_AUTH' AND TABLE_NAME='CF_SELLER_BUSINESS_HISTORY';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE CF_AUTH.CF_SELLER_BUSINESS_HISTORY(
 HISTORY_ID VARCHAR2(36) PRIMARY KEY,SELLER_ID VARCHAR2(100) NOT NULL,MARKETPLACE_ID VARCHAR2(36) NOT NULL,
 RECORD_VERSION NUMBER(10) NOT NULL CHECK(RECORD_VERSION>0),DATA_ID VARCHAR2(100) NOT NULL UNIQUE,
 IDENTITY_FIXTURE_ID VARCHAR2(100) NOT NULL UNIQUE,BUSINESS_REVIEWED NUMBER(1) NOT NULL CHECK(BUSINESS_REVIEWED IN(0,1)),
 PAYLOAD_JSON CLOB NOT NULL CHECK(PAYLOAD_JSON IS JSON),REQUEST_HASH VARCHAR2(64) NOT NULL,IDEMPOTENCY_KEY VARCHAR2(36) NOT NULL,
 SAVED_BY VARCHAR2(36) NOT NULL,SAVED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT CF_HISTORY_SELLER_FK FOREIGN KEY(SELLER_ID) REFERENCES CF_AUTH.CF_SELLER_PROFILES(SELLER_ID),
 CONSTRAINT CF_HISTORY_VERSION_UK UNIQUE(SELLER_ID,RECORD_VERSION),CONSTRAINT CF_HISTORY_REPLAY_UK UNIQUE(SELLER_ID,IDEMPOTENCY_KEY))';END IF;
END;
/
MERGE INTO CF_AUTH.CF_MARKETPLACE_REFERENCES D USING(SELECT '11111111-1111-4111-8111-111111111111' ID,'VS' PREFIX,1001 FIRST_NUMBER FROM DUAL UNION ALL SELECT '22222222-2222-4222-8222-222222222222','BB',2001 FROM DUAL) S ON(D.MARKETPLACE_ID=S.ID) WHEN NOT MATCHED THEN INSERT(MARKETPLACE_ID,REFERENCE_PREFIX,NEXT_NUMBER) VALUES(S.ID,S.PREFIX,S.FIRST_NUMBER);
DECLARE next_ref NUMBER;new_ref VARCHAR2(100);n NUMBER;BEGIN
 FOR market IN(SELECT * FROM CF_AUTH.CF_MARKETPLACE_REFERENCES ORDER BY MARKETPLACE_ID FOR UPDATE) LOOP
  SELECT GREATEST(market.NEXT_NUMBER,COALESCE(MAX(TO_NUMBER(REGEXP_SUBSTR(MARKETPLACE_SELLER_ID,'[0-9]+$')))+1,market.NEXT_NUMBER)) INTO next_ref FROM CF_AUTH.CF_SELLER_PROFILES WHERE MARKETPLACE_ID=market.MARKETPLACE_ID AND REGEXP_LIKE(MARKETPLACE_SELLER_ID,'^'||market.REFERENCE_PREFIX||'-[0-9]+$');
  FOR seller IN(SELECT SELLER_ID,MARKETPLACE_SELLER_ID FROM CF_AUTH.CF_SELLER_PROFILES WHERE MARKETPLACE_ID=market.MARKETPLACE_ID AND REGEXP_LIKE(MARKETPLACE_SELLER_ID,'^S-[0-9a-fA-F-]{36}$') ORDER BY CREATED_AT,SELLER_ID) LOOP
   new_ref:=market.REFERENCE_PREFIX||'-'||TO_CHAR(next_ref,'FM0000');
   IF next_ref>=10000 THEN new_ref:=market.REFERENCE_PREFIX||'-'||TO_CHAR(next_ref,'FM999999999999');END IF;
   UPDATE CF_AUTH.CF_SELLER_PROFILES SET MARKETPLACE_SELLER_ID=new_ref WHERE SELLER_ID=seller.SELLER_ID;
   SELECT COUNT(*) INTO n FROM CF_APPLICATION.CF_SELLER_MAPPINGS WHERE MARKETPLACE_ID=market.MARKETPLACE_ID AND MARKETPLACE_SELLER_ID=new_ref;
   IF n=0 THEN INSERT INTO CF_APPLICATION.CF_SELLER_MAPPINGS(MARKETPLACE_ID,MARKETPLACE_SELLER_ID,SELLER_ID) VALUES(market.MARKETPLACE_ID,new_ref,seller.SELLER_ID);END IF;
   DBMS_OUTPUT.PUT_LINE(seller.MARKETPLACE_SELLER_ID||' -> '||new_ref);next_ref:=next_ref+1;
  END LOOP;
  UPDATE CF_AUTH.CF_MARKETPLACE_REFERENCES SET NEXT_NUMBER=next_ref WHERE MARKETPLACE_ID=market.MARKETPLACE_ID;
 END LOOP;
END;
/
-- Auth owns history and scoped mappings; the local provider may only read immutable snapshots.
GRANT SELECT,INSERT,UPDATE ON CF_CONSENT.CF_FINANCIAL_PROVIDER_MAP TO CF_AUTH;
GRANT SELECT,INSERT,UPDATE ON CF_CONSENT.CF_SELLER_IDENTITY_MAP TO CF_AUTH;
GRANT SELECT ON CF_SIM_FINANCIAL.CF_MOCK_FINANCIAL_RECORD TO CF_AUTH;
GRANT SELECT ON CF_AUTH.CF_SELLER_BUSINESS_HISTORY TO CF_SIM_FINANCIAL;
COMMIT;
EXIT;
