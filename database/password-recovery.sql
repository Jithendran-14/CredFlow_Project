WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;
ALTER SESSION SET CONTAINER=FREEPDB1;
DECLARE n NUMBER; BEGIN
 SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='CF_AUTH' AND TABLE_NAME='CF_PASSWORD_RESET_TOKENS';
 IF n=0 THEN
  EXECUTE IMMEDIATE 'CREATE TABLE CF_AUTH.CF_PASSWORD_RESET_TOKENS(TOKEN_HASH VARCHAR2(64) PRIMARY KEY,USER_ID NUMBER NOT NULL REFERENCES CF_AUTH.CF_AUTH_USERS(USER_ID),EMAIL_ADDRESS VARCHAR2(255) NOT NULL,ACCOUNT_VERSION NUMBER NOT NULL,CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,EXPIRES_AT TIMESTAMP WITH TIME ZONE NOT NULL,USED_AT TIMESTAMP WITH TIME ZONE)';
  EXECUTE IMMEDIATE 'CREATE INDEX CF_AUTH.IX_CF_RESET_USER ON CF_AUTH.CF_PASSWORD_RESET_TOKENS(USER_ID)';
 END IF;
 SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='CF_AUTH' AND TABLE_NAME='CF_PASSWORD_RESET_LIMITS';
 IF n=0 THEN
  EXECUTE IMMEDIATE 'CREATE TABLE CF_AUTH.CF_PASSWORD_RESET_LIMITS(KEY_HASH VARCHAR2(64) PRIMARY KEY,WINDOW_START TIMESTAMP WITH TIME ZONE NOT NULL,ATTEMPTS NUMBER NOT NULL)';
  EXECUTE IMMEDIATE 'CREATE INDEX CF_AUTH.IX_CF_RESET_LIMIT_WINDOW ON CF_AUTH.CF_PASSWORD_RESET_LIMITS(WINDOW_START)';
 END IF;
END;
/
