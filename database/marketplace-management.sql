 SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS WHERE OWNER='CF_AUTH' AND TABLE_NAME='CF_ORGANIZATIONS' AND COLUMN_NAME='ORGANIZATION_STATUS';
 IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE CF_AUTH.CF_ORGANIZATIONS ADD (ORGANIZATION_STATUS VARCHAR2(20) DEFAULT ''ACTIVE'' NOT NULL CHECK(ORGANIZATION_STATUS IN (''ACTIVE'',''INACTIVE'')), ROW_VERSION NUMBER(19) DEFAULT 0 NOT NULL, CREATE_KEY VARCHAR2(100) UNIQUE, CREATE_HASH VARCHAR2(64))';END IF;
 SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS WHERE OWNER='CF_AUTH' AND TABLE_NAME='CF_SELLER_PROFILES' AND COLUMN_NAME='ROW_VERSION';
 IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE CF_AUTH.CF_SELLER_PROFILES ADD ROW_VERSION NUMBER(19) DEFAULT 0 NOT NULL';END IF;
 SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS WHERE OWNER='CF_AUTH' AND TABLE_NAME='CF_AUTH_USERS' AND COLUMN_NAME='PROFILE_VERSION';
 IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE CF_AUTH.CF_AUTH_USERS ADD PROFILE_VERSION NUMBER(19) DEFAULT 0 NOT NULL';END IF;
END;
