-- Run as the local Oracle administrator after creating CF_SIM_BANK_C with a password matching private runtime settings.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;
ALTER SESSION SET CONTAINER=FREEPDB1;
DECLARE n NUMBER;ddl CLOB;BEGIN
 SELECT COUNT(*) INTO n FROM DBA_USERS WHERE USERNAME='CF_SIM_BANK_C';
 IF n=0 THEN RAISE_APPLICATION_ERROR(-20001,'Create CF_SIM_BANK_C first and set db.bank-c.password in the private runtime settings.');END IF;
 EXECUTE IMMEDIATE 'GRANT CREATE SESSION,CREATE TABLE,CREATE SEQUENCE TO CF_SIM_BANK_C';
 EXECUTE IMMEDIATE 'ALTER USER CF_SIM_BANK_C QUOTA 100M ON USERS';
 DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM,'STORAGE',FALSE);
 DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM,'SEGMENT_ATTRIBUTES',FALSE);
 FOR t IN (SELECT TABLE_NAME FROM ALL_TABLES WHERE OWNER='CF_SIM_BANK_A' ORDER BY TABLE_NAME) LOOP
  SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='CF_SIM_BANK_C' AND TABLE_NAME=t.TABLE_NAME;
  IF n=0 THEN ddl:=REPLACE(DBMS_METADATA.GET_DDL('TABLE',t.TABLE_NAME,'CF_SIM_BANK_A'),'"CF_SIM_BANK_A"','"CF_SIM_BANK_C"');EXECUTE IMMEDIATE ddl;END IF;
 END LOOP;
END;
/
COMMIT;
EXIT;
