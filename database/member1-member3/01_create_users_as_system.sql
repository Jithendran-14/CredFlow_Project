SET ECHO OFF
SET VERIFY OFF
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE
WHENEVER OSERROR EXIT FAILURE

BEGIN
  IF SYS_CONTEXT('USERENV', 'SESSION_USER') <> 'SYSTEM' THEN
    RAISE_APPLICATION_ERROR(-20001, 'Connect as SYSTEM to the application PDB first.');
  END IF;
  IF SYS_CONTEXT('USERENV', 'CON_NAME') IN ('CDB$ROOT', 'PDB$SEED') THEN
    RAISE_APPLICATION_ERROR(-20002, 'Reconnect directly to the application PDB service, not the root/seed.');
  END IF;
END;
/

-- SYSTEM already exists and is the only administrative account used here.
-- This script does not create a database instance or change SYSTEM's password.
-- Change these names only if your DBA uses different EXISTING tablespaces.
DEFINE DATA_TABLESPACE = USERS
DEFINE TEMP_TABLESPACE = TEMP

DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM DBA_TABLESPACES
    WHERE TABLESPACE_NAME = UPPER('&DATA_TABLESPACE')
      AND CONTENTS = 'PERMANENT' AND STATUS = 'ONLINE';
  IF n <> 1 THEN
    RAISE_APPLICATION_ERROR(-20003, 'Configured permanent tablespace must exist and be ONLINE.');
  END IF;
  SELECT COUNT(*) INTO n FROM DBA_TABLESPACES
    WHERE TABLESPACE_NAME = UPPER('&TEMP_TABLESPACE') AND CONTENTS = 'TEMPORARY';
  IF n <> 1 THEN
    RAISE_APPLICATION_ERROR(-20004, 'Configured temporary tablespace must exist.');
  END IF;
  SELECT COUNT(*) INTO n FROM DBA_USERS WHERE USERNAME IN
    ('CF_ORCHESTRATION','CF_LENDER_INTEGRATION','CF_SIM_BANK_A','CF_SIM_NBFC_B');
  IF n <> 0 THEN
    RAISE_APPLICATION_ERROR(-20005, 'Fresh installation only: one or more service users already exist. Nothing was created.');
  END IF;
END;
/

-- Enter distinct passwords that satisfy your Oracle password profile.
-- For these SQL*Plus substitutions, do not use double quotes or ampersands.
-- Do not enable ECHO/VERIFY or spool this password-input section.
ACCEPT ORCH_PASSWORD CHAR PROMPT 'New CF_ORCHESTRATION password: ' HIDE
ACCEPT INT_PASSWORD CHAR PROMPT 'New CF_LENDER_INTEGRATION password: ' HIDE
ACCEPT BANK_PASSWORD CHAR PROMPT 'New CF_SIM_BANK_A password: ' HIDE
ACCEPT NBFC_PASSWORD CHAR PROMPT 'New CF_SIM_NBFC_B password: ' HIDE

CREATE USER CF_ORCHESTRATION IDENTIFIED BY "&ORCH_PASSWORD"
  DEFAULT TABLESPACE &DATA_TABLESPACE
  TEMPORARY TABLESPACE &TEMP_TABLESPACE
  QUOTA 500M ON &DATA_TABLESPACE
  ACCOUNT UNLOCK;
GRANT CREATE SESSION TO CF_ORCHESTRATION;
UNDEFINE ORCH_PASSWORD

CREATE USER CF_LENDER_INTEGRATION IDENTIFIED BY "&INT_PASSWORD"
  DEFAULT TABLESPACE &DATA_TABLESPACE
  TEMPORARY TABLESPACE &TEMP_TABLESPACE
  QUOTA 500M ON &DATA_TABLESPACE
  ACCOUNT UNLOCK;
GRANT CREATE SESSION TO CF_LENDER_INTEGRATION;
UNDEFINE INT_PASSWORD

CREATE USER CF_SIM_BANK_A IDENTIFIED BY "&BANK_PASSWORD"
  DEFAULT TABLESPACE &DATA_TABLESPACE
  TEMPORARY TABLESPACE &TEMP_TABLESPACE
  QUOTA 500M ON &DATA_TABLESPACE
  ACCOUNT UNLOCK;
GRANT CREATE SESSION TO CF_SIM_BANK_A;
UNDEFINE BANK_PASSWORD

CREATE USER CF_SIM_NBFC_B IDENTIFIED BY "&NBFC_PASSWORD"
  DEFAULT TABLESPACE &DATA_TABLESPACE
  TEMPORARY TABLESPACE &TEMP_TABLESPACE
  QUOTA 500M ON &DATA_TABLESPACE
  ACCOUNT UNLOCK;
GRANT CREATE SESSION TO CF_SIM_NBFC_B;
UNDEFINE NBFC_PASSWORD

-- SYSTEM creates owner-qualified objects in the following scripts.
-- Runtime owners can use their own tables/sequences without ANY/DBA grants.
UNDEFINE DATA_TABLESPACE
UNDEFINE TEMP_TABLESPACE
PROMPT Four service users created. Continue with 02_create_tables_as_system.sql.
