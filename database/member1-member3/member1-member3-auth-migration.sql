-- Run while connected as CF_AUTH in FREEPDB1.
-- Adds integration identity fields; preserves users, passwords and tables.
WHENEVER SQLERROR EXIT SQL.SQLCODE
DECLARE
  n NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV','CURRENT_SCHEMA') <> 'CF_AUTH' THEN
    RAISE_APPLICATION_ERROR(-20001,'Connect as CF_AUTH, or set CURRENT_SCHEMA=CF_AUTH first');
  END IF;
  SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS
    WHERE OWNER='CF_AUTH' AND TABLE_NAME='CF_AUTH_USERS' AND COLUMN_NAME='LENDER_ID';
  IF n=0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE CF_AUTH.CF_AUTH_USERS ADD (LENDER_ID VARCHAR2(100))';
  END IF;
  SELECT COUNT(*) INTO n FROM ALL_CONSTRAINTS
    WHERE OWNER='CF_AUTH' AND TABLE_NAME='CF_AUTH_USERS' AND CONSTRAINT_NAME='CK_CF_AUTH_ROLE';
  IF n>0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE CF_AUTH.CF_AUTH_USERS DROP CONSTRAINT CK_CF_AUTH_ROLE';
  END IF;
  EXECUTE IMMEDIATE q'[ALTER TABLE CF_AUTH.CF_AUTH_USERS ADD CONSTRAINT CK_CF_AUTH_ROLE
    CHECK (USER_ROLE IN ('ADMIN','SELLER','MARKETPLACE','VERIFICATION_SERVICE',
    'ELIGIBILITY_SERVICE','ORCHESTRATION_SERVICE','INTEGRATION_SERVICE',
    'LENDER_SERVICE','LENDER_OFFICER'))]';
END;
/
