-- Additive migration: durable seller requests and recorded initial marketplace sharing.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;
ALTER SESSION SET CONTAINER=FREEPDB1;
DECLARE N NUMBER; BEGIN
 SELECT COUNT(*) INTO N FROM ALL_TABLES WHERE OWNER='CF_AUTH' AND TABLE_NAME='CF_MARKETPLACE_LOAN_REQUESTS';
 IF N=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE CF_AUTH.CF_MARKETPLACE_LOAN_REQUESTS (
 REQUEST_ID VARCHAR2(36) PRIMARY KEY, SELLER_ID VARCHAR2(100) NOT NULL,
 SELLER_SUBJECT VARCHAR2(36) NOT NULL, MARKETPLACE_ID VARCHAR2(36) NOT NULL,
 IDEMPOTENCY_KEY VARCHAR2(100) NOT NULL, REQUEST_FINGERPRINT VARCHAR2(64) NOT NULL,
 REQUESTED_AMOUNT NUMBER(19,2) NOT NULL CHECK(REQUESTED_AMOUNT>0),
 LOAN_PURPOSE VARCHAR2(30) NOT NULL, SHARING_AUTHORISED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
 NOTICE_VERSION VARCHAR2(30) NOT NULL, PAYLOAD_JSON CLOB NOT NULL CHECK(PAYLOAD_JSON IS JSON),
 STATUS VARCHAR2(30) DEFAULT ''QUEUED'' NOT NULL CHECK(STATUS IN (''QUEUED'',''PROCESSING'',''RETRY_PENDING'',''SUBMITTED'',''ACTION_REQUIRED'')),
 APPLICATION_ID VARCHAR2(36), ATTEMPTS NUMBER DEFAULT 0 NOT NULL,
 NEXT_ATTEMPT_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 LEASE_UNTIL TIMESTAMP WITH TIME ZONE, CLAIM_TOKEN VARCHAR2(36), LAST_ERROR VARCHAR2(100),
 CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT CF_LOAN_REQUEST_SELLER_FK FOREIGN KEY(SELLER_ID) REFERENCES CF_AUTH.CF_SELLER_PROFILES(SELLER_ID),
 CONSTRAINT CF_LOAN_REQUEST_KEY_UK UNIQUE(SELLER_ID,IDEMPOTENCY_KEY))';
 EXECUTE IMMEDIATE 'CREATE INDEX CF_AUTH.CF_LOAN_REQUEST_DUE_IX ON CF_AUTH.CF_MARKETPLACE_LOAN_REQUESTS(STATUS,NEXT_ATTEMPT_AT)'; END IF;
END;
/
EXIT;
