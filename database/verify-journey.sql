-- Read-only proof of persistence. Run as SYSTEM in FREEPDB1, or use each schema's own queries.
-- Replace the UUID below with the PUBLIC application ID shown in the UI.
DEFINE application_id = 'ea978769-33d5-4c69-be76-98d8df1c0d87'
SET LINESIZE 220 PAGESIZE 100
SELECT PUBLIC_APPLICATION_ID, BUSINESS_NAME, STATUS, WORKFLOW_VERSION
FROM CF_APPLICATION.CF_APPLICATIONS WHERE PUBLIC_APPLICATION_ID='&&application_id';
SELECT STATUS, HEALTH FROM CF_ORCHESTRATION.CF_WORKFLOW
WHERE ID=HEXTORAW(REPLACE('&&application_id','-',''));
SELECT STATUS, ACKNOWLEDGEMENT, AMOUNT FROM CF_ORCHESTRATION.CF_OFFER
WHERE APPLICATION_ID=HEXTORAW(REPLACE('&&application_id','-',''));
SELECT STATUS, ELIGIBILITY_RESULT_ID FROM CF_ELIGIBILITY.ELIGIBILITY_OPERATION
WHERE APPLICATION_ID='&&application_id';
SELECT OUTCOME, TOTAL_GROSS, TOTAL_RETURNS, TOTAL_PAYOUT FROM CF_ELIGIBILITY.FINANCIAL_SNAPSHOT
WHERE APPLICATION_ID='&&application_id';
SELECT COUNT(*) AS AUDIT_EVENT_COUNT FROM CF_AUDIT.AUDIT_EVENT
WHERE APPLICATION_ID='&&application_id';
UNDEFINE application_id
