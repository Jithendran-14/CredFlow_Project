-- Run as SYS/SYSTEM in FREEPDB1. No existing business data is modified.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE n NUMBER;
BEGIN
 SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS WHERE OWNER='CF_ORCHESTRATION' AND TABLE_NAME='CF_WORKFLOW' AND COLUMN_NAME='FINANCIAL_PERMISSION_JSON';
 IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE CF_ORCHESTRATION.CF_WORKFLOW ADD (FINANCIAL_PERMISSION_JSON CLOB)'; END IF;
END;
/
